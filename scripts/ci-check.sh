#!/usr/bin/env bash
# Проверяет формат, vet, обычные тесты и гонки без изменения исходников.
set -euo pipefail
export GOWORK=off
paths=(cmd internal)
[[ ! -d tests ]] || paths+=(tests)
unformatted="$(find "${paths[@]}" -type f -name '*.go' -print0 | xargs -0 gofmt -l)"
if [[ -n "$unformatted" ]]; then printf '%s\n' "$unformatted"; exit 1; fi
go vet ./...
go test -count=1 -timeout 120s ./...
go test -race -count=1 -timeout 120s ./...
go build ./...
